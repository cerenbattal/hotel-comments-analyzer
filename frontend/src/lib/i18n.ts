/** Right-to-left languages. */
export const RTL: ReadonlySet<Lang> = new Set<Lang>(["ar"]);

/** Locale for formatting numbers; Arabic keeps Latin digits so they match the scores. */
export function numberLocale(lang: Lang): string {
  return lang === "ar" ? "ar-u-nu-latn" : lang;
}

export type Strings = (typeof strings)["en"];

export function t(lang: Lang): Strings {
  return strings[lang] as Strings;
}

export function parseLang(value: string | null | undefined): Lang {
  return LANGS.some((l) => l.code === value) ? (value as Lang) : "tr";
}
